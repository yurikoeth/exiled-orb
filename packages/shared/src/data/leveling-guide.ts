/** Get the leveling guide for a game */
export function getLevelingGuide(game: Game): LevelingGuide {
  return game === "poe1" ? POE1_LEVELING : POE2_LEVELING;
}

/**
 * Steps whose zone is this zone. An exact (case-insensitive) name wins over
 * a substring match so "The Sceptre of God" is not picked for "The Upper
 * Sceptre of God".
 */
function matchingSteps(guide: LevelingGuide, zoneName: string): LevelingStep[] {
  const lower = zoneName.toLowerCase();
  const exact = guide.steps.filter((s) => s.zone.toLowerCase() === lower);
  if (exact.length > 0) return exact;
  return guide.steps.filter((s) => lower.includes(s.zone.toLowerCase()));
}

/**
 * Find the current step for a zone. When the campaign reuses a zone name
 * (The Twilight Strand in Act 1 and Act 6), `charLevel` picks the latest
 * occurrence the character has reached via `minLevel`; without a level the
 * first occurrence is returned.
 */
export function findCurrentStep(
  guide: LevelingGuide,
  zoneName: string,
  charLevel?: number | null
): LevelingStep | null {
  const matches = matchingSteps(guide, zoneName);
  if (matches.length === 0) return null;
  if (charLevel == null) return matches[0];
  let best = matches[0];
  for (const step of matches) {
    if ((step.minLevel ?? 0) <= charLevel) best = step;
  }
  return best;
}

/** Get the step after the current one for a zone */
export function getNextStep(
  guide: LevelingGuide,
  zoneName: string,
  charLevel?: number | null
): LevelingStep | null {
  const current = findCurrentStep(guide, zoneName, charLevel);
  if (!current) return null;
  const idx = guide.steps.indexOf(current);
  return idx >= 0 && idx < guide.steps.length - 1 ? guide.steps[idx + 1] : null;
}
